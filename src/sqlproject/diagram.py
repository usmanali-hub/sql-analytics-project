"""Generate documentation from the live database: a Mermaid ER diagram and a data profile."""

from __future__ import annotations

import re
import sqlite3

from .db import columns, foreign_keys, null_counts, row_counts, table_names


def _mermaid_type(sql_type: str) -> str:
    base = re.sub(r"\(.*\)", "", sql_type).strip().lower() or "text"
    return re.sub(r"[^a-z0-9_]", "_", base)


def mermaid_er(conn: sqlite3.Connection) -> str:
    """ER diagram in Mermaid syntax, which GitHub renders directly in Markdown.

    A foreign key that cannot be NULL is drawn as "exactly one parent" (``||``); a nullable one as
    "zero or one parent" (``|o``). Every child can have many rows per parent (``o{``).
    """
    lines = ["erDiagram"]
    for table in table_names(conn):
        lines.append(f"    {table} {{")
        fks = {fk.column for fk in foreign_keys(conn) if fk.table == table}
        for col in columns(conn, table):
            key = "PK" if col.primary_key else ("FK" if col.name in fks else "")
            lines.append(f"        {_mermaid_type(col.type)} {col.name}{(' ' + key) if key else ''}")
        lines.append("    }")
    for fk in foreign_keys(conn):
        parent = "|o" if fk.nullable else "||"
        lines.append(f'    {fk.ref_table} {parent}--o{{ {fk.table} : "{fk.column}"')
    return "\n".join(lines)


def schema_markdown(conn: sqlite3.Connection) -> str:
    return (
        "# Schema\n\nGenerated from the database by `python -m sqlproject docs`; do not edit by hand.\n\n"
        "```mermaid\n" + mermaid_er(conn) + "\n```\n\n"
        "`||--o{` means one parent row has many child rows and every child must have a parent; "
        "`|o--o{` means the parent is optional.\n"
    )


def profile_markdown(conn: sqlite3.Connection) -> str:
    counts = row_counts(conn)
    rows = ["| Table | Rows | Columns | Columns containing NULLs |", "|---|---|---|---|"]
    for table in table_names(conn):
        nulls = {c: n for c, n in null_counts(conn, table).items() if n}
        detail = ", ".join(f"{c} ({n})" for c, n in nulls.items()) or "none"
        rows.append(f"| {table} | {counts[table]:,} | {len(columns(conn, table))} | {detail} |")
    return "# Data profile\n\nGenerated by `python -m sqlproject docs`.\n\n" + "\n".join(rows) + "\n"
