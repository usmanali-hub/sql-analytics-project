"""Load the .sql files in queries/, run them read-only and render the results."""

from __future__ import annotations

import csv
import re
import sqlite3
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
QUERY_DIR = ROOT / "queries"


@dataclass(frozen=True)
class Query:
    number: int
    name: str
    question: str
    notes: str
    sql: str


@dataclass(frozen=True)
class Result:
    columns: list[str]
    rows: list[tuple[object, ...]]


def parse_query(path: Path) -> Query:
    """Read a query file whose leading comments hold `-- question:` and `-- notes:` lines."""
    match = re.match(r"(\d+)_(.+)\.sql$", path.name)
    if not match:
        raise ValueError(f"query file names must look like 01_name.sql, got {path.name}")
    text = path.read_text(encoding="utf-8")
    meta = dict(re.findall(r"^--\s*(question|notes):\s*(.+)$", text, re.MULTILINE))
    if "question" not in meta:
        raise ValueError(f"{path.name} is missing a '-- question:' line")
    sql = "\n".join(line for line in text.splitlines() if not line.startswith("--")).strip()
    return Query(int(match.group(1)), match.group(2), meta["question"], meta.get("notes", ""), sql)


def load_queries(directory: Path = QUERY_DIR) -> list[Query]:
    queries = [parse_query(p) for p in sorted(directory.glob("*.sql"))]
    numbers = [q.number for q in queries]
    if len(set(numbers)) != len(numbers):
        raise ValueError("duplicate query numbers")
    return queries


def run_query(conn: sqlite3.Connection, query: Query) -> Result:
    cursor = conn.execute(query.sql)
    return Result([d[0] for d in cursor.description], cursor.fetchall())


def write_csv(result: Result, path: Path) -> None:
    with path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerow(result.columns)
        writer.writerows(result.rows)


def markdown_table(result: Result, max_rows: int = 12) -> str:
    def cell(value: object) -> str:
        return "" if value is None else str(value).replace("|", "\\|")

    lines = ["| " + " | ".join(result.columns) + " |", "|" + "|".join("---" for _ in result.columns) + "|"]
    lines += ["| " + " | ".join(cell(v) for v in row) + " |" for row in result.rows[:max_rows]]
    if len(result.rows) > max_rows:
        lines.append(f"\n_{len(result.rows)} rows in total; first {max_rows} shown. Full result in `results/`._")
    return "\n".join(lines)


def render_report(conn: sqlite3.Connection, queries: list[Query]) -> str:
    parts = ["# Business questions\n\nGenerated by `python -m sqlproject report`; each query lives in `queries/` and its full result in `results/`.\n"]
    for q in queries:
        parts.append(
            f"\n## {q.number}. {q.question}\n\n{q.notes}\n\n```sql\n{q.sql}\n```\n\n{markdown_table(run_query(conn, q))}\n"
        )
    return "".join(parts)


def write_outputs(conn: sqlite3.Connection, queries: list[Query], results_dir: Path, report_path: Path) -> None:
    results_dir.mkdir(parents=True, exist_ok=True)
    for q in queries:
        write_csv(run_query(conn, q), results_dir / f"{q.number:02d}_{q.name}.csv")
    report_path.write_text(render_report(conn, queries), encoding="utf-8")
